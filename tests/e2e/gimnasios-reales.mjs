// Directorio D: reclamación revisada, edición del titular y exclusión territorial. Solo datos sintéticos en la base de CI.
import { PrismaClient } from "@prisma/client";
import { B, rnd, browser, newUser, hacerAdmin, seen, check, terminarDiagnosticos } from "./ayudas.mjs";
const db = new PrismaClient();
const owner = await newUser("GymOwner");
const moderator = await newUser("GymModerator"); hacerAdmin(moderator.email);
const ownerUser = await db.user.findUniqueOrThrow({ where: { email: owner.email } });
const gym = await db.gym.create({ data: { name: `Gimnasio OSM prueba ${rnd}`, slug: `gym-osm-prueba-${rnd}`, city: "Madrid", province: "Madrid", source: "OSM", sourceRef: `node/${rnd}`, sourceLicense: "ODbL-1.0", disciplines: ["BOXEO"], lat: 40.4, lng: -3.7, geoSource: "osm" } });
await owner.p.goto(B + `/mis-gimnasios?q=${encodeURIComponent(gym.name)}`);
const found = owner.p.getByRole("region", { name: "Gimnasios encontrados" }).locator('article', { hasText: gym.name });
await found.locator('summary').click();
await found.locator('[name=evidence]').fill("Soy responsable del gimnasio; web oficial aportada para revisión.");
await found.locator('[name=evidenceUrl]').fill("https://gym-prueba.example");
await found.getByRole("button", { name: "Solicitar la reclamación", exact: true }).click();
await owner.p.locator('.notice-ok').waitFor();
check("la reclamación no asigna propiedad antes de revisión", (await db.gym.findUniqueOrThrow({ where: { id: gym.id } })).ownerUserId === null);
await moderator.p.goto(B + "/moderacion/gimnasios");
const claim = moderator.p.locator('#reclamaciones article', { hasText: gym.name });
await claim.locator('[name=note]').fill("Web oficial y relación comprobadas en este caso de prueba.");
await claim.getByRole("button", { name: "Aprobar reclamación", exact: true }).click();
await moderator.p.locator('.notice-ok').waitFor();
check("la aprobación concede propiedad y protege la ficha frente a importaciones", (await db.gym.findUniqueOrThrow({ where: { id: gym.id } })).ownerUserId === ownerUser.id);
await owner.p.goto(B + `/mis-gimnasios?gimnasio=${gym.id}`);
const manage = owner.p.getByRole("region", { name: "Gestionar gimnasio", exact: true });
await manage.locator('form').filter({ has: owner.p.getByRole("button", { name: "Guardar gimnasio", exact: true }) }).locator('[name=phone]').fill("913456789");
await manage.getByRole("button", { name: "Guardar gimnasio", exact: true }).click();
await owner.p.locator('.notice-ok').waitFor();
await owner.p.goto(B + `/gimnasios/${gym.slug}`);
check("el dato profesional editado se publica y se conserva la atribución ODbL", await seen(owner.p.getByRole("link", { name: "913456789", exact: true })) && await owner.p.locator('a[href="https://www.openstreetmap.org/copyright"]').count() > 0);
// Alta manual en provincia excluida: permanece para revisar y no entra ni en la ficha ni en el mapa/lista.
await moderator.p.goto(B + "/mis-gimnasios");
await moderator.p.locator('#alta summary').click();
const create = moderator.p.locator('#alta form');
await create.locator('[name=name]').fill(`Gym excluido ${rnd}`);
await create.locator('[name=city]').fill("Barcelona");
await create.locator('[name=province]').selectOption("Barcelona");
await create.getByRole("button", { name: "Guardar gimnasio", exact: true }).click();
await moderator.p.locator('.notice-ok').waitFor();
const excluded = await db.gym.findFirstOrThrow({ where: { name: `Gym excluido ${rnd}` } });
check("alta manual excluida queda por revisar", excluded.status === "PENDING");
check("la ficha excluida responde 404", (await owner.p.request.get(B + `/gimnasios/${excluded.slug}`)).status() === 404);
await owner.p.goto(B + `/gimnasios?q=${encodeURIComponent(excluded.name)}`);
check("la búsqueda y mapa no publican el gimnasio excluido", await owner.p.locator('a[href="/gimnasios/' + excluded.slug + '"]').count() === 0);
await terminarDiagnosticos(); await db.$disconnect(); await browser.close();
